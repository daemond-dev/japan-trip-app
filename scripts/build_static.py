#!/usr/bin/env python3
"""Build the static site (GitHub Pages) into site/: the app page with the data bundled in, running in the same
mode the Android app uses offline, plus a web manifest and a service worker so it can be added to the home screen
and opened without a connection. No claude.ai account needed; no Ask, no live sync, no shared to-dos.
Usage: python3 scripts/build_static.py [data dir] [out dir]   (defaults: data, site)"""
import os, sys, json, shutil, subprocess, datetime
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "data")
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "site")
shutil.rmtree(out, ignore_errors=True); os.makedirs(out)
subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "patch_html.py"), os.path.join(ROOT, "app", "index.html"), os.path.join(out, "index.html")], check=True)
subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "make_data.py"), data, os.path.join(out, "data.js")], check=True)
shutil.copy(os.path.join(ROOT, "android", "assets", "www", "shim.js"), os.path.join(out, "shim.js"))
open(os.path.join(out, ".nojekyll"), "w").close()

# Icons from the Android launcher art.
from PIL import Image
src = Image.open(os.path.join(ROOT, "android", "res", "mipmap-xxxhdpi", "ic_launcher.png")).convert("RGBA")
src.resize((192, 192), Image.LANCZOS).save(os.path.join(out, "icon-192.png"))
src.resize((512, 512), Image.LANCZOS).save(os.path.join(out, "icon-512.png"))

meta = json.load(open(os.path.join(data, "meta.json"), encoding="utf-8"))
title = meta.get("title") or "Japan trip"
json.dump({"name": title, "short_name": title[:12], "start_url": "./", "scope": "./", "display": "standalone",
           "background_color": "#f3f4f6", "theme_color": "#1f2937", "lang": "en",
           "icons": [{"src": "icon-192.png", "sizes": "192x192", "type": "image/png"},
                     {"src": "icon-512.png", "sizes": "512x512", "type": "image/png"}]},
          open(os.path.join(out, "manifest.webmanifest"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

build = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d-%H%M%S")
files = ["./", "index.html", "data.js", "shim.js", "manifest.webmanifest", "icon-192.png", "icon-512.png"]
open(os.path.join(out, "sw.js"), "w", encoding="utf-8").write('''/* Service worker for the static site: precaches the app, serves network-first (5 s) with the cache as the
   fallback, so the site is fresh when online and still opens when offline. Generated by scripts/build_static.py. */
const BUILD = "%s";
const CACHE = "trip-" + BUILD;
const FILES = %s;
self.addEventListener("install", e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener("activate", e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener("fetch", e => {
  const req = e.request;
  if(req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    try{
      const ctrl = new AbortController(); const t = setTimeout(() => ctrl.abort(), 5000);
      const res = await fetch(req, {signal: ctrl.signal}); clearTimeout(t);
      if(res && res.ok) cache.put(req, res.clone());
      return res;
    }catch(err){
      return (await cache.match(req, {ignoreSearch: true})) || (req.mode === "navigate" ? await cache.match("index.html") : null) || Response.error();
    }
  })());
});
''' % (build, json.dumps(files)))

# Head tags for installing, and the worker registration at the end of the page's own body.
page = open(os.path.join(out, "index.html"), encoding="utf-8").read()
head = ('<link rel="manifest" href="manifest.webmanifest">\n<meta name="theme-color" content="#1f2937">\n'
        '<meta name="mobile-web-app-capable" content="yes">\n<meta name="apple-mobile-web-app-capable" content="yes">\n'
        '<meta name="apple-mobile-web-app-status-bar-style" content="default">\n<meta name="apple-mobile-web-app-title" content="%s">\n'
        '<link rel="apple-touch-icon" href="icon-192.png">\n' % title.replace('"', "&quot;"))
page = page.replace("<head>", "<head>\n" + head, 1)
reg = ('<script>\n(function(){\n  if(!("serviceWorker" in navigator)) return;\n'
       '  if(location.protocol !== "https:" && location.hostname !== "localhost" && location.hostname !== "127.0.0.1") return;\n'
       '  addEventListener("load", function(){ navigator.serviceWorker.register("sw.js").catch(function(){}); });\n})();\n</script>\n')
i = page.rfind("</body>"); assert i > 0
page = page[:i] + reg + page[i:]
open(os.path.join(out, "index.html"), "w", encoding="utf-8").write(page)
print("static site in", out, "build", build)
